export function riverX(z: number) {
  return 47 + Math.sin(z * 0.037) * 3 + Math.sin(z * 0.09) * 1.2;
}
export function terrainHeight(x: number, z: number, walkable = true) {
  const hill = 18 * Math.exp(-((x + 62) ** 2 / 900 + (z + 86) ** 2 / 660));
  const shrine = 3.8 * Math.exp(-((x - 80) ** 2 / 700 + (z + 73) ** 2 / 750));
  let h = hill + shrine;
  if (Math.abs(x) < 32 && z > -59) h = 0;
  if (Math.abs(x - riverX(z)) < 5.1) h = -1.1;
  for (const [cx, cz, w, d] of PADDIES) if (Math.abs(x - cx) < w / 2 && Math.abs(z - cz) < d / 2) h = -0.5;
  if (z > -29 && z < -23 && x > 36 && x < 56) h = 0.18;
  if (walkable) {
    const base = 3.8 * Math.exp(-(9 / 700 + 4 / 750));
    if (Math.abs(x - 77) < 0.87 && z < -71.67 && z > -75.58)
      h = Math.max(h, base + 0.19 * Math.min(9, 1 + Math.floor((-z - 71.67) / 0.42)));
    if (Math.abs(x - 77) < 1.62 && z <= -75.48 && z > -78.4) h = Math.max(h, base + 1.74);
  }
  let ground = cityTerrain(x, z, sampleRegionTerrain(x, z, h));
  // A bridge carries travelers over the river; its invisible terrain must not form a dam.
  if(!walkable && z < -132 && regionBridgeAt(x,z)) {
    const river=regionRiverSample(z),distance=Math.abs(x-river.x);
    if(distance<river.halfWidth+1) {
      const t=Math.min(1,Math.max(0,(distance-river.halfWidth+1)/2));
      ground=(river.y-1.6)*(1-t)+ground*t;
    }
  }
  return walkable ? ferrySupportHeight(x,z) ?? cityFloor(x, z, ground) : ferryGroundHeight(x,z,ground);
}
